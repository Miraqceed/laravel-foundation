<?php

namespace Miraqceed\Foundation\Attempts;

/**
 * 枠の数え方（照合が成功したときの扱い）
 */
enum Counting
{
    /** 失敗だけを数える本人の枠（アカウントごとなど）。成功したら枠を空にする */
    case FailuresOwn;

    /**
     * 失敗だけを数える共有の枠（接続元ごとなど）。成功したら今回の1回分だけ返す。
     * 空にすると、自分のアカウントを持つ攻撃者が合間に成功するだけで、共有の枠を戻せる
     */
    case FailuresShared;

    /** 試みを全部数える（お金の掛かる試みなど）。成功しても返さない。結果の後に数えると、同時の要求がどれも上限の手前で通る */
    case Every;
}
